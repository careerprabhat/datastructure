package com.ds.A_Numbers;

public class C_Range {
    public static void main(String[] args) {
        System.out.println(Byte.MIN_VALUE);//-128, 1byte
        System.out.println(Byte.MAX_VALUE);//127
        System.out.println(Integer.MAX_VALUE);//2147483647, 4bytes
        System.out.println(Integer.MIN_VALUE);//-2147483648
        System.out.println(Long.MIN_VALUE);//-9223372036854775808, 8bytes
        System.out.println(Long.MAX_VALUE); //9223372036854775807
    }


}
